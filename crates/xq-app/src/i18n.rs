/// Difficulty index (0..=3) to its Vietnamese name.
#[must_use]
pub fn difficulty_name(d: u8) -> &'static str {
    match d {
        0 => t(Key::DiffEasy),
        2 => t(Key::DiffHard),
        3 => t(Key::DiffMaster),
        4 => t(Key::DiffCustom),
        _ => t(Key::DiffMedium),
    }
}
